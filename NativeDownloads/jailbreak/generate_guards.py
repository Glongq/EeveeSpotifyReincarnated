"""Derive jailbreak guards from the frozen v7 IPA patchers; no duplicated offsets."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import patch_native_restrictions as r
import patch_key_request_mode as k

def array(name, data):
    return f'static const unsigned char {name}[] = {{{",".join(hex(b) for b in data)}}};\n'

def source():
    out = '// Generated by generate_guards.py from the v7 IPA patchers.\n#pragma once\n'
    for name, data in [('JB_UUID',r.UUID), ('JB_SetterOriginal',r.ORIGINAL),
        ('JB_Trampoline',r.trampoline()), ('JB_KeyOriginal',k.ORIGINAL),
        ('JB_Provider',k.PROVIDER_HEAD), ('JB_Mapping',k.MAPPING_BYTES),
        ('JB_SetterPatched',r.branch(r.SETTER,r.CAVE).to_bytes(4,'little')),
        ('JB_KeyPatched',bytes.fromhex('02008052')), ('JB_Dlsym',k.DLSYM_STUB_HEAD)]:
        out += array(name,data)
    for name, address in [('Setter',r.SETTER),('Cave',r.CAVE),('KeyWindow',k.WINDOW),
        ('KeyCall',k.CALL_SITE),('Provider',k.PROVIDER),('Mapping',k.MAPPING),('Dlsym',k.DLSYM_STUB)]:
        out += f'#define JB_{name}Offset {hex(address-r.PREFERRED)}UL\n'
    return out

if __name__ == '__main__':
    path=Path(__file__).with_name('Guards.h')
    if '--check' in sys.argv:
        assert path.read_text()==source(), 'Regenerate jailbreak Guards.h'
    else:
        path.write_text(source())
